import { z } from "zod";

// =============================================================================
// Evidence Category Types
// =============================================================================

/**
 * Evidence categories map to the different systems/sources at a hotel
 * that can provide evidence for dispute responses.
 */
export const EvidenceCategorySchema = z.enum([
  "pms_data", // Property Management System data (folios, registration cards)
  "policy", // Cancellation, refund, terms policies
  "proof_of_stay", // Check-in/out records, keycard logs, housekeeping
  "communications", // Email, chat, phone logs, confirmations
  "payment_data", // Authorization, settlement, AVS/CVV data
  "incident_reports", // Damage reports, complaints, incident logs
  "delivery", // Shipping/tracking (rarely used in hotels)
  "other", // Miscellaneous evidence
]);

export type EvidenceCategory = z.infer<typeof EvidenceCategorySchema>;

// =============================================================================
// Evidence Requirement Types
// =============================================================================

/**
 * Status of an individual evidence requirement
 */
export const EvidenceRequirementStatusSchema = z.enum([
  "pending", // Not yet uploaded
  "uploaded", // File has been uploaded
  "not_available", // Marked as not available by user
  "not_applicable", // Doesn't apply to this dispute
]);

export type EvidenceRequirementStatus = z.infer<
  typeof EvidenceRequirementStatusSchema
>;

/**
 * Individual evidence requirement generated by the AI
 */
export const EvidenceRequirementSchema = z.object({
  id: z.string(),
  category: EvidenceCategorySchema,
  label: z.string(),
  tag: z.string().optional(), // Structured identifier for dedup (e.g., "folio", "cancellation_policy", "registration_card")
  description: z.string(),
  example: z.string().optional(),
  sourceHint: z.string().optional(), // Where to get this (e.g., "Front Desk", "Finance")
  instructions: z.string().optional(), // Specific actionable steps to gather this evidence
  required: z.boolean(),
  priority: z.number(), // 1 = highest priority
});

export type EvidenceRequirement = z.infer<typeof EvidenceRequirementSchema>;

