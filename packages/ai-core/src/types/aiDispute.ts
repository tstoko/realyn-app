/**
 * Initialize evidence items from a plan
 * Marks folio requirements as uploaded if folio is already available
 */
export function initializeEvidenceItems(
  plan: EvidencePlan,
  hasFolio: boolean = false,
  folioUrl?: string
): EvidenceItem[] {
  return plan.requirements.map((req) => {
    // If this is a folio requirement and folio is available, mark it as uploaded
    const isFolioRequirement =
      req.tag === "folio" ||
      (req.category === "pms_data" &&
       (req.label.toLowerCase().includes("folio") ||
        req.label.toLowerCase().includes("reservation folio")));
    
    if (isFolioRequirement && hasFolio) {
      return {
        requirementId: req.id,
        status: "uploaded" as const,
        fileName: folioUrl ? "Folio (from booking)" : "Folio",
        notes: folioUrl ? `Available from booking: ${folioUrl}` : "Available from booking",
      };
    }
    
    return {
      requirementId: req.id,
      status: "pending" as const,
    };
  });
}

